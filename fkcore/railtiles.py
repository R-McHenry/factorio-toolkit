def tiles(name, x, y, direction):
    """The tiles ``name`` at (x, y) facing ``direction`` takes, or None for a piece not measured."""
    shape = RAIL_TILES.get(name)
    if shape is None:
        return None
    d = int(direction or 0) % 16
    d -= d % 2
    if d not in shape:
        d %= 8
    fx, fy = int(x // 1), int(y // 1)
    return {(fx + dx, fy + dy) for dx, dy in shape[d]}
